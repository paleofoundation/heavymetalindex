#!/usr/bin/env node
// Emits Examine-style category SECTION pages + a directory index.
//
// PRODUCTS are taxonomy-driven (data/taxonomy/hmtc-v2.json): pages group by
// hmtc_category (the number, not the drifting category_label), master/summary
// pages are excluded, the category name comes from the taxonomy, and each
// category page is organized by SUBCATEGORY (a product's `category` field is its
// subcategory slug; variants prefix-match the taxonomy sub slug).
//
// INGREDIENTS group by a food-group rollup; METALS split into two groups and are
// listed inline (no sub-pages). The directory (/products, /ingredients) renders a
// lean grid of cards from data/category-index.json (this script's other output),
// each linking OUT to a section page.

import fs from "fs"
import path from "path"
import matter from "gray-matter"

const ROOT = process.cwd()
const WIKI = path.join(ROOT, "wiki")

const slugify = (s) =>
  String(s).toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "")

function readPages(dir, type) {
  const out = []
  const abs = path.join(WIKI, dir)
  if (!fs.existsSync(abs)) return out
  for (const name of fs.readdirSync(abs)) {
    if (!name.endsWith(".md") || name === "index.md") continue
    try {
      const { data } = matter(fs.readFileSync(path.join(abs, name), "utf8"))
      if (data?.type !== type) continue
      out.push({ slug: `${dir}/${name.replace(/\.md$/, "")}`, title: String(data.title ?? name.replace(/\.md$/, "")), fm: data })
    } catch {
      /* skip */
    }
  }
  return out
}

// ------------------------------------------------------------ PRODUCTS (taxonomy)
const TAX = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "taxonomy", "hmtc-v2.json"), "utf8"))
const catByNum = new Map(
  TAX.categories.map((c) => [
    c.n,
    {
      n: c.n,
      name: String(c.name).replace(/\s*\(Ages[^)]*\)/i, "").trim(),
      subs: (c.subcategories ?? []).map((s) => ({ row: s.row, name: s.name, slug: s.slug })),
    },
  ]),
)

const isMaster = (p) =>
  p.fm.hmtc_row_count != null || /master/i.test(p.title) || /master/i.test(p.slug)

// group leaf products by hmtc_category number
const byCatNum = new Map()
for (const p of readPages("products", "product-category")) {
  if (isMaster(p)) continue
  const n = typeof p.fm.hmtc_category === "number" ? p.fm.hmtc_category : null
  if (n == null) continue
  ;(byCatNum.get(n) ?? byCatNum.set(n, []).get(n)).push(p)
}

const productGroups = []
for (const [n, pages] of [...byCatNum.entries()].sort((a, b) => a[0] - b[0])) {
  const cat = catByNum.get(n)
  const label = cat?.name ?? `Category ${n}`
  const subs = cat?.subs ?? []
  // Assign each product to a subcategory. The page FILENAME is the taxonomy sub
  // slug for most pages (fish-freshwater, canned-seafood); variants prefix-match
  // (infant-formula-powder-non-soy -> infant-formula-powder). The `category`
  // frontmatter field is only populated ~44% of the time, so it is the fallback.
  const findSub = (cand) => {
    if (!cand) return null
    const ex = subs.find((s) => s.slug === cand)
    if (ex) return ex
    let best = null
    for (const s of subs) if (cand.startsWith(s.slug + "-") && (!best || s.slug.length > best.slug.length)) best = s
    return best
  }
  const subMap = new Map()
  const unmatched = []
  for (const p of pages) {
    const base = String(p.slug).split("/").pop()
    const s = findSub(base) ?? findSub(String(p.fm.category ?? ""))
    if (s) {
      const b = subMap.get(s.slug) ?? { row: s.row, name: s.name, members: [] }
      b.members.push({ slug: p.slug, title: p.title })
      subMap.set(s.slug, b)
    } else unmatched.push({ slug: p.slug, title: p.title })
  }
  const subList = [...subMap.values()].sort((a, b) => a.row - b.row)
  for (const s of subList) s.members.sort((a, b) => a.title.localeCompare(b.title))
  if (unmatched.length)
    subList.push({ row: 999, name: "Other", members: unmatched.sort((a, b) => a.title.localeCompare(b.title)) })
  productGroups.push({ slug: slugify(label), label, count: pages.length, subs: subList })
}

function writeProductPages(groups) {
  const dir = path.join(WIKI, "products", "categories")
  fs.mkdirSync(dir, { recursive: true })
  for (const f of fs.readdirSync(dir)) if (f.endsWith(".md")) fs.unlinkSync(path.join(dir, f)) // clear stale
  for (const g of groups) {
    let body =
      `---\ntitle: ${g.label}\ntype: category-index\nparent_vertical: products\n` +
      `description: Products in the ${g.label} category (${g.count}), by subcategory.\n---\n\n` +
      `<!-- generated by tools/build-category-pages.mjs -->\nProduct pages in **${g.label}**, organized by subcategory.\n\n`
    for (const s of g.subs) {
      // A subcategory with a single product IS that product — render it as a
      // linked heading (no redundant duplicate bullet). Multi-variant
      // subcategories get a plain heading with the variants beneath. The catch-all
      // "Other" bucket always uses bullets.
      if (s.members.length === 1 && s.name !== "Other") {
        body += `## [[${s.members[0].slug}|${s.name}]]\n\n`
      } else {
        body += `## ${s.name}\n\n` + s.members.map((m) => `- [[${m.slug}|${m.title}]]`).join("\n") + `\n\n`
      }
    }
    fs.writeFileSync(path.join(dir, `${g.slug}.md`), body)
  }
  return groups.length
}

// ------------------------------------------------------------ INGREDIENTS (rollup)
