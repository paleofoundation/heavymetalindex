test("2026-10-21 hub-only deposit records Malaysia, Kenya, EU curdlan, and Luxembourg rows", () => {
  const intakeId = "rw-intake-2026-10-21-reg-watch"
  const intake = intakes.find((item) => item.intake_id === intakeId)
  const owned = events.filter((event) => event.intake_id === intakeId)
  assert.equal(events.length, 28)
  assert.equal(intake.cluster_count, 4)
  assert.equal(intake.sha256, "4d911199dec32775817e7ff1786b5721f336eb3a366a03bc538480be0ff875ae")
  assert.equal(owned.length, 4)
  assert.deepEqual(owned.map((event) => event.cluster), [1, 2, 3, 4])

  const malaysia = byId.get("rw-2026-10-21-my-pua-48-2026")
  const kenya = byId.get("rw-2026-10-21-ken-2121-cascara")
  const curdlan = byId.get("rw-2026-10-21-eu-2026-2298-curdlan")
  const luxembourg = byId.get("rw-2026-10-21-lu-rgd-2026-07-24-metal-alloy-fcm")

  assert.equal(malaysia.hub_rows.length, 21)
  assert.equal(kenya.hub_rows.length, 5)
  assert.equal(curdlan.hub_rows.length, 2)
  assert.equal(luxembourg.hub_rows.length, 25)

  for (const event of [malaysia, kenya, curdlan, luxembourg]) {
    assert.equal(event.disposition, "hub-only")
    assert.equal(event.verification.state, "verified-primary")
    assert.equal(event.article_slugs.length, 0)
    assert.deepEqual(event.hmi_routes.regulatory_limit_ids, [])
    const prose = `${event.title}\n${event.summary}\n${event.verification.notes}\n${JSON.stringify(event.hub_rows)}`
    assert.equal(prose.includes("\u2014"), false, event.event_id)
    assert.equal(prose.toLowerCase().includes("hmtc"), false, event.event_id)
    assert.equal(prose.toLowerCase().includes("certification"), false, event.event_id)
    assert.equal(prose.toLowerCase().includes("natural mineral water"), false, event.event_id)
  }

  assert.equal(malaysia.status, "in-force")
  assert.equal(malaysia.dates.effective, "2026-08-01")
  assert.equal(malaysia.hub_rows[0].manifest_id, "RW-2026-10-011")
  assert.equal(malaysia.hub_rows[0].value_as_printed, "")
  const flat = malaysia.hub_rows.filter((item) => item.criterion_status === "conflict")
  assert.deepEqual(flat.map((item) => item.manifest_id), ["RW-2026-10-011g", "RW-2026-10-011h"])
  for (const item of flat) {
    assert.match(item.display, /purata/)
    assert.match(item.display, /1479/)
    assert.match(item.display, /min/)
    assert.match(item.display, /1484/)
    assert.match(item.display, /Neither reading is chosen/)
  }
  assert.equal(flat[0].value_as_printed, "0.8")
  assert.equal(flat[1].value_as_printed, "0.07")
  const unnamed = malaysia.hub_rows.filter((item) => item.matrix_as_printed === "unnamed in amending text")
  assert.deepEqual(unnamed.map((item) => item.manifest_id), ["RW-2026-10-011i", "RW-2026-10-011j"])
  assert.match(unnamed[0].display, /unnamed in the amending text/)
  assert.match(unnamed[1].display, /species is not stated/i)
  assert.equal(malaysia.analytes.includes("Cr-total"), true)
  assert.equal(malaysia.analytes.includes("Cr-VI"), false)
  assert.equal(malaysia.analytes.includes("iAs"), false)
  assert.equal(malaysia.analytes.includes("tAs"), false)

  assert.equal(kenya.status, "consultation")
  assert.equal(kenya.dates.published, "2026-10-20")
  assert.equal(kenya.dates.consultation_close, "2026-12-17")
  assert.equal(kenya.dates.next_review, "2026-12-18")
  assert.equal(kenya.dates.adopted, null)
  assert.equal(kenya.dates.effective, null)
  assert.deepEqual(kenya.analytes, ["Cd", "Pb", "Cu", "Hg-species-not-stated", "As-species-not-stated"])
  assert.equal(kenya.analytes.includes("iAs"), false)
  assert.equal(kenya.analytes.includes("tHg"), false)
  const kenyaProse = `${kenya.title}\n${kenya.summary}\n${kenya.verification.notes}`.toLowerCase()
  assert.equal(kenyaProse.includes("in force"), false)
  assert.equal(kenyaProse.includes("effective"), false)
  assert.equal(kenyaProse.includes("binding"), false)
  assert.match(kenya.verification.notes, /cadmium 0\.05/)
  assert.match(kenya.verification.notes, /arsenic 0\.2/)
  assert.match(kenya.verification.notes, /Table 3/)

  assert.equal(curdlan.status, "adopted-not-effective")
  assert.equal(curdlan.dates.published, "2026-10-19")
  assert.equal(curdlan.dates.effective, "2026-11-08")
  assert.equal(curdlan.dates.next_review, "2026-11-09")
  assert.deepEqual(curdlan.hub_rows.map((item) => item.value_as_printed), ["Not more than 0,05", "Not more than 0,2"])
  assert.equal(curdlan.analytes.includes("iAs"), false)
  assert.equal(curdlan.analytes.includes("tAs"), false)
  assert.match(curdlan.verification.notes, /twentieth day/)

  assert.equal(luxembourg.status, "in-force")
  assert.equal(luxembourg.dates.published, "2026-10-08")
  assert.equal(luxembourg.dates.effective, "2026-10-12")
  assert.equal(luxembourg.hub_rows.find((item) => item.manifest_id === "RW-2026-10-008a").value_as_printed, "5")
  assert.equal(luxembourg.hub_rows.find((item) => item.manifest_id === "RW-2026-10-008d").value_as_printed, "1*")
  assert.equal(luxembourg.hub_rows.find((item) => item.manifest_id === "RW-2026-10-008y").value_as_printed, "60")
  assert.equal(luxembourg.hub_rows.find((item) => item.manifest_id === "RW-2026-10-008w").value_as_printed, "0,010")
  assert.equal(luxembourg.analytes.includes("Cr-VI"), true)
  assert.equal(luxembourg.analytes.includes("Cr-total"), false)
  assert.match(luxembourg.official_sources[0].url, /pdfa/)
  assert.match(luxembourg.verification.notes, /59e0055d8eb982da88f172e2e60223d18bc862bbc181d6bf54ba56c0fa8920ac/)
  assert.match(luxembourg.summary, /no earlier hub event/i)
})

