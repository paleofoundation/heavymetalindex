#!/usr/bin/env node
/**
 * Ingredient synthesis-backlog detector.
 *
 * The failure this closes: a source page can declare an ingredient and a metal
 * in its frontmatter (so it lands in the ingredient's source legend), yet the
 * ingredient's contamination_profile is never re-synthesized to consume it. The
 * profile stays frozen at its bootstrap n while the legend accumulates dozens of
 * sources. Black-pepper carried Pb at n=2 with eight sources reporting black-
 * pepper lead; nothing surfaced the gap because the only synthesis-needs queue
 * in the repo (cells-needing-synthesis.csv) is dead — generated by no tool.
 *
 * This detector is the missing surfacing step. For every (ingredient, metal) it
 * compares:
 *   available  = source pages whose frontmatter declares BOTH this ingredient
 *                (via an [[ingredients/<slug>]] backlink) AND this metal
 *   synthesized = n_studies recorded in the ingredient's contamination_profile
 * and flags the cell when meaningful evidence sits unsynthesized.
 *
 * `available` is an UPPER BOUND: a source can declare an ingredient generally
 * (e.g. a multi-spice survey) without reporting an ingredient-specific row, so a
 * flagged cell is a candidate for a synthesis pass to read the sources, not a
 * guarantee that all `available` sources carry usable values. That read is the
 * synthesis workflow's job; this detector's job is to make the candidate visible.
 *
 * Deterministic, no LLM, no network. Output is a queue, not an approval gate.
 *
 * Usage:
 *   node tools/evidence/audit-ingredient-synthesis-backlog.mjs           # write CSV + print top backlog
 *   node tools/evidence/audit-ingredient-synthesis-backlog.mjs --check   # exit 1 if any severe-starvation cell exists
 */

import fs from "node:fs"
import path from "node:path"
import matter from "gray-matter"

const REPO = process.cwd()
const INGREDIENTS_DIR = path.join(REPO, "wiki/ingredients")
const SOURCES_DIR = path.join(REPO, "wiki/sources")
const OUT_CSV = path.join(REPO, "data/evidence/ingredient-synthesis-backlog.csv")
const METALS = ["Pb", "Cd", "iAs", "tAs", "tHg", "Ni", "Al", "Cr", "Sn", "U"]
const CHECK = process.argv.includes("--check")

// A cell is backlogged when at least GAP more sources are available than have
// been synthesized AND there are at least MIN_AVAIL sources to work with. A cell
// is SEVERE when many sources are available but ~nothing has been synthesized.
const GAP = 2
const MIN_AVAIL = 3
const SEVERE_AVAIL = 5
const SEVERE_SYNTH = 1

// ---- 1. Build the source backlink index: ingredient-slug -> metal -> count ----
const avail = new Map() // slug -> Map(metal -> Set(cite_key))
function bump(slug, metal, cite) {
  if (!avail.has(slug)) avail.set(slug, new Map())
  const m = avail.get(slug)
  if (!m.has(metal)) m.set(metal, new Set())
  m.get(metal).add(cite)
}

let sourcesScanned = 0
for (const file of fs.readdirSync(SOURCES_DIR).filter((f) => f.endsWith(".md"))) {
  let data
  try {
    data = matter(fs.readFileSync(path.join(SOURCES_DIR, file), "utf8")).data || {}
  } catch {
    continue
  }
  const ings = Array.isArray(data.ingredients) ? data.ingredients : []
  const metals = Array.isArray(data.metals) ? data.metals : []
  if (!ings.length || !metals.length) continue
  sourcesScanned += 1
  const cite = data.cite_key || file.replace(/\.md$/, "")
  const slugs = ings
    .map((w) => String(w).match(/ingredients\/([a-z0-9-]+)/i))
    .filter(Boolean)
    .map((m) => m[1])
  for (const slug of slugs) {
    for (const metal of metals) {
      if (METALS.includes(metal)) bump(slug, metal, cite)
    }
  }
}

// ---- 2. Compare against each ingredient's synthesized n_studies ----
const rows = []
let pagesScanned = 0
for (const file of fs.readdirSync(INGREDIENTS_DIR).filter((f) => f.endsWith(".md") && f !== "index.md")) {
  const slug = file.replace(/\.md$/, "")
  let data
  try {
    data = matter(fs.readFileSync(path.join(INGREDIENTS_DIR, file), "utf8")).data || {}
  } catch {
    continue
  }
  const cp = data.contamination_profile
  if (!cp || typeof cp !== "object") continue
  pagesScanned += 1
  const metalMap = avail.get(slug)
  if (!metalMap) continue
  for (const metal of METALS) {
    const available = metalMap.get(metal)?.size || 0
    if (available < MIN_AVAIL) continue
    const cell = cp[metal] || {}
    const synthesized = Number(cell.n_studies) || 0
    const gap = available - synthesized
    if (gap < GAP) continue
    const severe = available >= SEVERE_AVAIL && synthesized <= SEVERE_SYNTH
    rows.push({ slug, metal, synthesized, available, gap, severe })
  }
}

// ---- 3. Emit ----
rows.sort((a, b) => b.gap - a.gap || b.available - a.available)
const header = "ingredient,metal,synthesized_n,available_sources,gap,severity"
const csv = [header, ...rows.map((r) => `${r.slug},${r.metal},${r.synthesized},${r.available},${r.gap},${r.severe ? "severe" : "backlog"}`)]
fs.writeFileSync(OUT_CSV, csv.join("\n") + "\n", "utf8")

const severe = rows.filter((r) => r.severe)
const pagesAffected = new Set(rows.map((r) => r.slug)).size
console.log(
  `Synthesis backlog: ${sourcesScanned} sources indexed, ${pagesScanned} ingredient pages checked.\n` +
    `  ${rows.length} backlogged (ingredient,metal) cells across ${pagesAffected} pages; ${severe.length} severe.\n` +
    `  Wrote ${path.relative(REPO, OUT_CSV)}`,
)
// Top starved pages by total unsynthesized cells.
const byPage = {}
for (const r of rows) byPage[r.slug] = (byPage[r.slug] || 0) + 1
const top = Object.entries(byPage)
  .sort((a, b) => b[1] - a[1])
  .slice(0, 20)
console.log("  Most-starved pages (backlogged cells):")
for (const [slug, n] of top) console.log(`    ${slug}: ${n}`)

if (CHECK && severe.length > 0) {
  console.error(`\n${severe.length} severe-starvation cells (many sources, <=1 synthesized). Run a synthesis pass.`)
  process.exit(1)
}
