// ---------------------------------------------------------------------------
// Per-cell source provenance, parsed from each ingredient page's own table.
// ---------------------------------------------------------------------------
// Returns { [slug]: { table: { [analyte]: {n, typicalNums:[...], coverage} },
//                     sources: { [analyte]: [citeKey, ...] } } }
function parseIngredientTables() {
  const map = {}
  for (const file of fs.readdirSync(INGREDIENTS_DIR).filter((f) => f.endsWith(".md") && f !== "index.md" && !f.startsWith("_"))) {
    const slug = file.replace(/\.md$/, "")
    const raw = fs.readFileSync(path.join(INGREDIENTS_DIR, file), "utf8")
    const heading = raw.indexOf("## Heavy metal contamination profile")
    if (heading === -1) continue
    // The table block: from the heading to the next H2.
    const after = raw.slice(heading)
    const nextH2 = after.slice(3).search(/\n##\s/)
    const block = nextH2 === -1 ? after : after.slice(0, nextH2 + 3)

    const table = {}
    const sources = {}
    for (const line of block.split("\n")) {
      if (!line.startsWith("|")) continue
      // Skip header/separator rows.
      const first = line.split("|")[1]?.trim() ?? ""
      if (first === "Analyte" || /^-+$/.test(first)) continue
      const analyte = first
      if (!METALS.includes(analyte)) continue

      // Contributing source cite-keys: every [[sources/KEY|label]] on the row.
      const keys = []
      for (const m of line.matchAll(/\[\[sources\/([^\]|\\]+)(?:\\?\|[^\]]*)?\]\]/g)) {
        keys.push(m[1].trim())
      }
      sources[analyte] = keys

      // Numeric drift anchors: strip wikilinks first so escaped pipes don't
      // shred the cell split, then read Coverage + Typical columns.
      const clean = line.replace(/\[\[[^\]]*\]\]/g, "")
      const cells = clean.split("|").map((c) => c.trim())
      // cells: ["", analyte, coverage, typical, confidence, sources(empty)]
      const coverage = cells[2] ?? ""
      const typical = cells[3] ?? ""
      const nMatch = coverage.match(/n\s*=\s*(\d+)/i)
      const typicalNums = (typical.match(/-?\d+(?:\.\d+)?/g) || []).map(Number)
      const composites = coverage.match(/composites\s*=\s*(\d+)/i)
      table[analyte] = { n: nMatch ? Number(nMatch[1]) : null, composites: composites ? Number(composites[1]) : null, typicalNums, coverage, typical }
    }
    map[slug] = { table, sources }
  }
  return map
}

// ---------------------------------------------------------------------------
// Drift check: exported occurrence numbers must match the page table.
// ---------------------------------------------------------------------------
function driftCheck(contamination, tables) {
  const problems = [] // hard failures: a page CONTRADICTS the exported number, or a cite-key is dangling
  const warnings = [] // soft: page renders no table at all (frontmatter still authoritative)
  const sourceKeyExists = (key) => fs.existsSync(path.join(repoRoot, "wiki/sources", `${key}.md`))

  for (const rec of contamination.records) {
    const parsed = tables[rec.ingredient]
    if (!parsed) {
      // The export mirrors the authoritative `contamination_profile` frontmatter;
      // a page with no rendered table is a human-rendering coverage gap, not a
      // contradiction. Surface it, do not fail the build on it.
      warnings.push(`${rec.ingredient}: page renders no contamination table (frontmatter has data; body view is missing)`)
      continue
    }
    for (const [metal, cell] of Object.entries(rec.metals)) {
      if (!(cell.status === "populated" || cell.status === "in_progress")) continue
      if (cell.typical_ppb == null) continue
      const row = parsed.table[metal]
      if (!row) {
        problems.push(`${rec.ingredient}/${metal}: JSON has a populated value but the page table has no such row`)
        continue
      }
      // n_studies must match.
      if (cell.n_studies != null && row.n != null && cell.n_studies !== row.n) {
        problems.push(`${rec.ingredient}/${metal}: n_studies JSON=${cell.n_studies} page=${row.n}`)
      }
      if (cell.value_kind === "source_non_detect") {
        const count = (cell.evidence || []).filter((e) => e.role === "value").reduce((n, e) => n + Number(e.n || 0), 0)
        if (row.composites !== count) problems.push(`${rec.ingredient}/${metal}: composite count JSON=${count} page=${row.composites}`)
        if (row.typical !== renderNonDetect(cell)) problems.push(`${rec.ingredient}/${metal}: non-detect reporting-limit display disagrees with exported evidence`)
      }
      if (cell.value_kind === "unquantified" && row.typical !== "Not quantified") problems.push(`${rec.ingredient}/${metal}: unquantified profile rendered as a numeric claim`)
      if (cell.value_kind) {
        const expected = evidenceSources(cell).sort()
        const actual = [...new Set(parsed.sources[metal] || [])].sort()
        if (JSON.stringify(expected) !== JSON.stringify(actual)) problems.push(`${rec.ingredient}/${metal}: source provenance JSON=${expected.join(",")} page=${actual.join(",")}`)
      }
      // Every non-null typical endpoint must appear in the page's Typical cell.
      const endpoints = (Array.isArray(cell.typical_ppb) ? cell.typical_ppb : [cell.typical_ppb]).filter((v) => v != null)
      for (const v of endpoints) {
        const hit = row.typicalNums.some((n) => Math.abs(n - v) < 1e-6)
        if (!hit) {
          problems.push(`${rec.ingredient}/${metal}: typical ${v} not present in page cell "${row.typical}"`)
        }
      }
    }
    // Every exported source cite-key must resolve to a real source page.
    for (const keys of Object.values(parsed.sources)) {
      for (const key of keys) {
        if (!sourceKeyExists(key)) problems.push(`${rec.ingredient}: source cite-key "${key}" does not resolve to wiki/sources/${key}.md`)
      }
    }
  }
  return { problems, warnings }
}

// ---------------------------------------------------------------------------
// Build the occurrence dataset (contamination.json enriched with sources).
// ---------------------------------------------------------------------------
function buildOccurrence(contamination, tables) {
  const records = contamination.records.map((rec) => {
    const parsedSources = tables[rec.ingredient]?.sources || {}
    const analytes = {}
    for (const [metal, cell] of Object.entries(rec.metals)) {
      analytes[metal] = {
        ...profileEvidenceForExport(cell),
        status: cell.status ?? null,
        typical_ppb: cell.typical_ppb ?? null,
        p95_ppb: cell.p95_ppb ?? null,
        confidence: cell.confidence ?? null,
        n_studies: cell.n_studies ?? null,
        last_reviewed: cell.last_reviewed ?? null,
        sources: cell.value_kind ? evidenceSources(cell).map((k) => `sources/${k}`) : parsedSources[metal] ? parsedSources[metal].map((k) => `sources/${k}`) : [],
      }
    }
    return {
      ingredient: rec.ingredient,
      title: rec.title,
      commodity: rec.commodity ?? rec.ingredient,
      category: rec.category ?? null,
      aliases: rec.aliases ?? [],
      wiki_doi: rec.wiki_doi ?? null,
      page_url: rec.page_url ?? `${SITE}/ingredients/${rec.ingredient}`,
      sources_count: rec.sources_count ?? null,
      last_updated: rec.last_updated ?? null,
      analytes,
    }
  })
  return {
    schema_version: SCHEMA_VERSION,
    dataset: "hmi-occurrence",
    title: "Heavy Metal Index — food & ingredient occurrence data",
    description:
      "Measured heavy-metal occurrence distributions per ingredient and analyte (typical range, 95th percentile, study count, confidence, contributing sources), compiled from the peer-reviewed and regulatory literature. Values are in ppb (µg/kg) on the basis each source reported.",
    unit: "ppb (µg/kg)",
    analyte_panel: METALS,
    generated_at: generatedAt,
    generated_commit: generatedCommit,
    source_dataset_generated_at: contamination.generated_at ?? null,
    license: LICENSE,
    attribution: ATTRIBUTION,
    record_count: records.length,
    records,
  }
}

function occurrenceCsv(occurrence) {
  const header = [
    "ingredient",
    "title",
    "category",
    "analyte",
    "status",
    "typical_low_ppb",
    "typical_high_ppb",
    "p95_ppb",
    "confidence",
    "n_studies",
    "last_reviewed",
    "sources",
    "page_url",
    "value_kind",
    "evidence_json",
    "evidence_note",
    "basis_conversion_json",
  ]
  const rows = [header]
  for (const rec of occurrence.records) {
    for (const metal of METALS) {
      const cell = rec.analytes[metal]
      if (!cell) continue
      const typ = Array.isArray(cell.typical_ppb) ? cell.typical_ppb : cell.typical_ppb == null ? [null, null] : [cell.typical_ppb, cell.typical_ppb]
      rows.push([
        rec.ingredient,
        rec.title,
        rec.category ?? "",
        metal,
        cell.status ?? "",
        typ[0] ?? "",
        typ[1] ?? "",
        cell.p95_ppb ?? "",
        cell.confidence ?? "",
        cell.n_studies ?? "",
        cell.last_reviewed ?? "",
        (cell.sources || []).join("; "),
        rec.page_url,
        cell.value_kind ?? "",
        JSON.stringify(cell.evidence || []),
        cell.evidence_note ?? "",
        cell.basis_conversion ? JSON.stringify(cell.basis_conversion) : "",
      ])
    }
  }
  return toCsv(rows)
}

// ---------------------------------------------------------------------------
// Source corpus DOI locator — a published DOI → source-page map.
// ---------------------------------------------------------------------------
// This is the artifact that lets the certification site (heavymetalcertified.com)
// deep-link an inline citation to the Heavy Metal Index source page that carries
// that document's structured record, WITHOUT breaching the one-way firewall: the
// cert consumes this PUBLIC index (like any reader), and never reads Index private
// data. It is literature-native (bibliographic locator + our public evidence tier),
// carries no certification threshold, and only maps DOIs that resolve to a live,
// public /sources/<slug> page. Pending sources and drafts use the same exclusion
// rule as the page build. The key is a bare, lowercased DOI (10.xxxx/yyyy); DOIs are
// case-insensitive, so consumers must lowercase before lookup.
function normalizeDoi(raw) {
  if (raw == null) return null
  let s = String(raw)
    .trim()
    .replace(/^["']|["']$/g, "")
    .trim()
    .toLowerCase()
  s = s
    .replace(/^https?:\/\/(dx\.)?doi\.org\//, "")
    .replace(/^doi:\s*/, "")
    .trim()
    .replace(/[).,;>\]]+$/, "") // trailing punctuation / brackets from prose
  return /^10\.\d{4,9}\/\S+$/.test(s) ? s : null // rejects the template's 10.xxxx/xxxxx
}

function frontmatterBlock(raw) {
  if (!raw.startsWith("---")) return ""
  const end = raw.indexOf("\n---", 3)
  return end === -1 ? "" : raw.slice(3, end)
}
function fmValue(block, key) {
  const m = block.match(new RegExp(`^${key}:[ \\t]*(.+?)[ \\t]*$`, "m"))
  return m ? m[1].replace(/^["']|["']$/g, "").trim() : null
}

function buildSources() {
  const byDoi = {}
  const rows = []
  let scanned = 0
  let collisions = 0
  for (const file of fs
    .readdirSync(SOURCES_DIR)
    .filter((f) => f.endsWith(".md") && f !== "index.md" && !f.startsWith("_"))) {
    const raw = fs.readFileSync(path.join(SOURCES_DIR, file), "utf8")
    const block = frontmatterBlock(raw)
    if (!block) continue
    const slug = file.replace(/\.md$/, "")
    if (!isPublicWikiRecord(matter(raw).data, `sources/${slug}`)) continue
    scanned++
    const doi = normalizeDoi(fmValue(block, "doi"))
    if (!doi) continue
    const title = fmValue(block, "title") || slug
    const tier = fmValue(block, "evidence_tier") || null
    const yearRaw = fmValue(block, "year")
    const year = yearRaw && /^\d{4}$/.test(yearRaw) ? Number(yearRaw) : null
    if (byDoi[doi]) {
      // DOI-collision dedup (tools/dedup-doi-clusters.mjs) has already collapsed
      // same-work duplicates upstream; a residual collision here is a wrong-DOI
      // mis-ingest. First wins deterministically; count for the build log.
      collisions++
      continue
    }
    // The JSON map is a lean locator (the cert fetches it client-side): slug is
    // all a consumer needs to build the page URL; tier/year are cheap trust/context.
    // The human-readable title stays in the CSV so the tabular open-data form is
    // self-describing without bloating the hot runtime path.
    byDoi[doi] = { slug, tier, year }
    rows.push({ doi, slug, title, tier, year })
  }
  rows.sort((a, b) => a.doi.localeCompare(b.doi))
  const envelope = {
    schema_version: SCHEMA_VERSION,
    dataset: "hmi-sources",
    title: "Heavy Metal Index — source corpus DOI locator",
    description:
      "A DOI → source-page map for the Heavy Metal Index corpus: every peer-reviewed and regulatory document with a resolvable DOI that has a live source page, keyed by bare lowercased DOI, with the page slug, public evidence tier, and year. Lets any client resolve a DOI to its record on heavymetalindex.com/sources/{slug}. Document titles are carried in the companion sources.csv.",
    site: SITE,
    page_url_template: `${SITE}/sources/{slug}`,
    generated_at: generatedAt,
    generated_commit: generatedCommit,
    license: LICENSE,
    attribution: ATTRIBUTION,
    record_count: rows.length,
    by_doi: byDoi,
  }
  return { envelope, rows, stats: { scanned, mapped: rows.length, collisions } }
}

function sourcesCsv(rows) {
  const header = ["doi", "slug", "title", "tier", "year", "page_url"]
  const out = [header]
  for (const r of rows) {
    out.push([r.doi, r.slug, r.title, r.tier ?? "", r.year ?? "", `${SITE}/sources/${r.slug}`])
  }
  return toCsv(out)
}

