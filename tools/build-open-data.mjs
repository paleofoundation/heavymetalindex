#!/usr/bin/env node
/**
 * build-open-data.mjs — the machine-readable open-data surface for the
 * literature-native layer of heavymetalindex.com.
 *
 * WHAT IT PUBLISHES
 * -----------------
 * A single, versioned, self-describing bundle under wiki/static/data/ (served
 * at /static/data/… via Quartz's Assets emitter, exactly like the existing
 * /static/contamination.json). This is the "open data" answer-engines and
 * downstream QA/retail systems consume, and the target of the schema.org
 * DataCatalog markup injected on the /data page (tools/postbuild-open-data.mjs).
 *
 *   wiki/static/data/occurrence.json  — per-(ingredient × analyte) occurrence
 *       distribution: typical range, p95, n_studies, confidence, AND the
 *       contributing source cite-keys (parsed from each ingredient page's own
 *       contamination table, so the export carries the same provenance the
 *       reader sees). Superset of /static/contamination.json.
 *   wiki/static/data/occurrence.csv   — the same data, tidy/long (one row per
 *       ingredient × analyte cell).
 *   wiki/static/data/regulations.json — the regulatory-limit corpus, re-stamped
 *       from /static/regulations.json with the same version envelope.
 *   wiki/static/data/regulations.csv  — tidy/long (one row per regulation).
 *   wiki/static/data/catalog.json     — a schema.org-shaped DataCatalog manifest
 *       listing every distribution, its license, version, and provenance. The
 *       machine index for the whole surface.
 *
 * FIREWALL (CLAUDE.md Part 2 / Part 19)
 * -------------------------------------
 * This surface is LITERATURE-NATIVE ONLY: measured occurrence and published
 * regulatory limits. It carries NO HMTc certification threshold, no pooled
 * P97/P45 derivation, no clean/dirty designation. Those live on the cert site
 * and cite this surface one-way; nothing here references them.
 *
 * SOURCE OF TRUTH / NO DRIFT
 * --------------------------
 * Occurrence numbers come from wiki/static/contamination.json (itself derived
 * from the ingredient-page `contamination_profile` frontmatter by
 * build-contamination-dataset.mjs, earlier in prebuild). Per-cell sources come
 * from the rendered "Heavy metal contamination profile" table on each ingredient
 * page. Because both the table and contamination.json derive from the same
 * frontmatter (the table is regenerated by build-ingredient-contamination-
 * tables.mjs --apply, which must run before this tool), the drift check below
 * asserts the exported numbers match the numbers on the page. A mismatch fails
 * the build.
 *
 * USAGE
 *   node tools/build-open-data.mjs            # emit the bundle (+ inline drift check)
 *   node tools/build-open-data.mjs --check    # drift check only, emit nothing, exit 1 on drift
 *   node tools/build-open-data.mjs --warn-only # emit, but never fail on drift
 */

