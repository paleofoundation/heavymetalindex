function regulationsCsv(reg) {
  const header = [
    "rule_id",
    "title",
    "jurisdictions",
    "agency",
    "program",
    "metals",
    "matrices",
    "limit_value",
    "limit_unit",
    "status",
    "effective_date",
    "sunset_date",
    "source_refs",
    "page_url",
  ]
  const rows = [header]
  for (const r of reg.records) {
    rows.push([
      r.rule_id ?? r.slug ?? "",
      r.title ?? "",
      asList(r.jurisdictions ?? r.jurisdiction).join("; "),
      r.agency ?? "",
      r.program ?? "",
      asList(r.metals ?? r.metal).join("; "),
      asList(r.matrices ?? r.matrix).join("; "),
      r.limit_value ?? "",
      r.limit_unit ?? "",
      r.status ?? "",
      isoDate(r.effective_date),
      isoDate(r.sunset_date),
      asList(r.source_refs).join("; "),
      r.page_url ?? "",
    ])
  }
  return toCsv(rows)
}

