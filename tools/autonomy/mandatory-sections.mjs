const ingredientFailures = []
const productFailures = []
const filesChanged = []

if (fs.existsSync(ingredientsDir)) auditDir(ingredientsDir, "ingredient")
if (fs.existsSync(productsDir)) auditDir(productsDir, "product")

function auditDir(dir, kind) {
  for (const file of fs.readdirSync(dir)) {
    if (!file.endsWith(".md") || file === "index.md") continue
    auditFile(path.join(dir, file), kind)
  }
}

function auditFile(filepath, kind) {
  const text = fs.readFileSync(filepath, "utf8")
  if (!text.startsWith("---")) return
  const fmEnd = text.indexOf("\n---", 4)
  if (fmEnd < 0) return
  const fmText = text.slice(4, fmEnd)
  const body = text.slice(fmEnd + 4)
  const slug = path.basename(filepath, ".md")
  const rel = path.relative(repoRoot, filepath)

  if (isStub(fmText, body, kind)) return

  const required = kind === "ingredient" ? INGREDIENT_SECTIONS : PRODUCT_SECTIONS
  const missing = required.filter((s) => !sectionPresent(body, s))
  if (missing.length === 0) return

  const failures = kind === "ingredient" ? ingredientFailures : productFailures
  failures.push({ file: rel, slug, missing })

  if (dryRun) return

  let newBody = body
  // Insert missing sections at the end of the body, before any trailing whitespace
  let trailing = ""
  while (newBody.endsWith("\n")) {
    trailing = "\n" + trailing
    newBody = newBody.slice(0, -1)
  }
  const additions = []
  for (const section of missing) {
    if (sectionPresent(newBody, section)) continue
    additions.push(`\n## ${section}\n\n${getPlaceholder(section, slug)}\n`)
  }
  if (additions.length === 0) return
  const out = text.slice(0, fmEnd + 4) + newBody + additions.join("") + trailing
  fs.writeFileSync(filepath, out, "utf8")
  filesChanged.push(rel)
}

function isStub(fmText, body, kind) {
  if (kind === "ingredient") {
    // Stub if all contamination_profile sub-blocks are `status: pending`
    // AND the page declares `sources: 0` (or omits the field)
    const pendingMatches = fmText.match(/status:\s*pending/g)
    const populatedMatches = fmText.match(/status:\s*(?:populated|in_progress)/g)
    if (populatedMatches && populatedMatches.length > 0) return false
    if (pendingMatches && pendingMatches.length >= 8) return true
  }
  if (kind === "product") {
    // Stub if `sources: 0` or no sources field
    const m = fmText.match(/^sources:\s*(\d+)$/m)
    if (!m) return true
    return Number(m[1]) === 0
  }
  return false
}

function sectionPresent(body, sectionTitle) {
  // Normalize the title so minor formatting variance (spaces around slashes,
  // hyphen vs en-dash, trailing punctuation) doesn't produce false positives.
  // We compare H2 headings in the body against the required-title set after
  // both are normalized.
  const headings = []
  for (const line of body.split("\n")) {
    const m = line.match(/^##\s+(.+?)\s*$/)
    if (m) headings.push(normalizeHeading(m[1]))
  }
  const target = normalizeHeading(sectionTitle)
  if (headings.includes(target)) return true

  // Variant matchers — pages that already cover the same content under a
  // narrower title satisfy the requirement. The "Why this commodity
  // accumulates heavy metals" section, for example, is satisfied by any
  // analyte-specific variant (cadmium, lead, arsenic, etc.) because the
  // underlying content explains the accumulation mechanism.
  if (target === "why this commodity accumulates heavy metals") {
    return headings.some((h) => /^why this commodity accumulates\b/.test(h))
  }
  if (target === "heavy metal contamination profile") {
    return headings.some((h) => /^contamination profile\b/.test(h)) || headings.some((h) => /heavy metal.*profile/.test(h))
  }
  return false
}

function normalizeHeading(s) {
  return s
    .toLowerCase()
    .replace(/[‐-―]/g, "-") // en-dash, em-dash → hyphen
    .replace(/\s*\/\s*/g, "/")
    .replace(/\s+/g, " ")
    .replace(/[.,;:!?]+$/g, "")
    .trim()
}

function getPlaceholder(section, slug) {
  const v = PLACEHOLDER_BY_SECTION[section]
  if (typeof v === "function") return v(slug)
  if (typeof v === "string") return v
  return "_Pending synthesis._"
}

