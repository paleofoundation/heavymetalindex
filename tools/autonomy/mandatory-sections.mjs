#!/usr/bin/env node
// Mandatory-sections audit + autofill per CLAUDE.md Part 6 (template) and
// Part 18 (lint check).
//
// Ingredient pages (non-stub) must carry these H2 headings:
//   1. Why this commodity accumulates heavy metals
//   2. Heavy metal contamination profile
//   3. Ranges by source, region, and variety
//   4. Processing effects
//   5. Ingredient-derivative risk
//   6. Mitigation options
//   7. Regulatory limits that apply
//   8. Sources
//
// Product-category pages (non-stub) must carry these H2 headings:
//   1. Who this page is for
//   2. Methodology
//   3. Literature Evidence Summary
//   4. Source Evidence Inventory
//   5. Broad Product Context: Author-Scope Index
//   6. Federal/Regulatory Limits vs Field Findings
//   7. Levers to reduce contamination
//   8. How standards math uses this page
//   9. Historical recalls and enforcement
//  10. Sources
//
// Stubs are exempt (untouched pages with no routed sources).
//
// The fix mode inserts placeholder sections so the structure passes lint and
// future synthesis sessions can fill in content. The placeholder text is
// explicit ("Pending synthesis. ...") so a brand-legal reader sees the page
// is incomplete rather than mistaking placeholder text for considered content.
//
// Usage:
//   node tools/autonomy/mandatory-sections.mjs            # audit + autofill
//   node tools/autonomy/mandatory-sections.mjs --dry-run  # audit only
//   node tools/autonomy/mandatory-sections.mjs --no-autofill   # audit only

