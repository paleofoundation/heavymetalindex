#!/usr/bin/env node
// tools/outstanding/render-findings.mjs — regenerate docs/findings.md from the ledger.
//
// docs/findings.md becomes a GENERATED VIEW of the outstanding-items ledger, so
// the historically-passive findings file is now a projection of a consumed,
// machine-readable structure. Do not hand-edit docs/findings.md. No model call.

import fs from "node:fs"
import { openItems, FINDINGS } from "./lib.mjs"

const MARK_BEGIN = "<!-- BEGIN: outstanding-ledger (generated by tools/outstanding/render-findings.mjs — do not hand-edit below) -->"
const MARK_END = "<!-- END: outstanding-ledger -->"

const items = openItems().sort((a, b) => (a.id < b.id ? 1 : -1)) // newest id first

function block(i) {
  const date = (i.id.match(/^OI-(\d{4})(\d{2})(\d{2})/) || []).slice(1).join("-") || i.ts.slice(0, 10)
  const lines = [
    `### ${i.id} — ${i.title}`,
    ``,
    `- scope: **${i.scope_class}** · type: ${i.type} · status: ${i.status} · repo: ${i.repo}${i.blocked_on.length ? ` · blocked_on: ${i.blocked_on.join(", ")}` : ""}`,
  ]
  if (i.target_paths.length) lines.push(`- paths: ${i.target_paths.map((p) => "`" + p + "`").join(", ")}`)
  if (i.repro) lines.push(`- repro: ${i.repro}`)
  if (i.acceptance_criteria.length) lines.push(`- done when: ${i.acceptance_criteria.join("; ")}`)
  if (i.evidence.length) lines.push(`- evidence: ${i.evidence.join(" · ")}`)
  if (i.scope_class === "human-gated") lines.push(`- decision: ${i.karen_decision ? "**" + i.karen_decision + "**" : "_pending_"}${i.one_command ? ` — enact: \`${i.one_command}\`` : ""}`)
  if (i.notes) lines.push(`- notes: ${i.notes}`)
  void date
  return lines.join("\n")
}

const generated = [
  MARK_BEGIN,
  ``,
  `# findings — outstanding-items ledger (generated)`,
  ``,
  `> Out-of-scope defects, gaps, and built-but-unshipped work, logged rather than chased.`,
  `> This file is a GENERATED VIEW of \`data/evidence/outstanding/ledger.jsonl\`. Do not edit it by hand —`,
  `> log with \`node tools/outstanding/log.mjs\` (or the \`<!-- OUTSTANDING: {json} -->\` sentinel the Stop-hook harvests),`,
  `> and rule on human-gated items with \`node tools/outstanding/decide.mjs <id> "APPROVE|DECLINE|DEFER: ..."\`.`,
  ``,
  `${openItems().length} open item(s): ${openItems().filter((i) => i.scope_class === "auto").length} auto, ${openItems().filter((i) => i.scope_class === "human-gated").length} awaiting a decision.`,
  ``,
  ...items.map(block).flatMap((b) => [b, ""]),
  MARK_END,
  ``,
].join("\n")

// Preserve any prose ABOVE the generated marker (legacy hand-written findings kept as history).
let preamble = ""
if (fs.existsSync(FINDINGS)) {
  const cur = fs.readFileSync(FINDINGS, "utf8")
  const idx = cur.indexOf(MARK_BEGIN)
  preamble = idx >= 0 ? cur.slice(0, idx) : (cur.trim() ? cur.trimEnd() + "\n\n---\n\n" : "")
}

fs.writeFileSync(FINDINGS, preamble + generated, "utf8")
console.log(`render-findings: wrote ${items.length} open items to ${FINDINGS.replace(process.cwd() + "/", "")}`)
