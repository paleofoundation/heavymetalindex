import test from "node:test"
import assert from "node:assert/strict"
import { assertPublicHtmlProcessingFree } from "./publicProcessing"

test("publication rejects internal callouts in headers, histories and evidence drawers", () => {
  for (const html of [
    '<p class="hero-stamp">Compiled by Codex AI · Scientific review incomplete</p>',
    '<section><h2>Update history</h2><p>AI compilation.</p></section>',
    '<details><p>AI source verification by Codex</p></details>',
    '<p>Compiled by <em>Codex</em> <strong>AI</strong></p>',
    '<button data-evidence="&lt;p&gt;AI source verification by Codex&lt;/p&gt;">Evidence</button>',
    '<meta name="description" content="Compiled by Codex AI">',
    '<p>Generated by AI.</p>',
    '<p>AI-powered evidence extraction.</p>',
  ]) assert.throws(() => assertPublicHtmlProcessingFree(html, "ingredients/rice"), /Internal processing text.*ingredients\/rice/)
})

test("scientific limitations, regulatory citations and scientific uses of AI remain valid", () => {
  assert.doesNotThrow(() => assertPublicHtmlProcessingFree(
    '<p>Outcome-level appraisal remains incomplete. Codex Alimentarius, Codex CXS 193-1995 and EU limits are cited. Compared with Codex limits; regulated by Codex. Adequate intake (AI): 65 µg/day. Authors: El-Batal AI.</p><script>const ai = 1 // Codex AI</script><!-- Internal Codex AI record -->',
    "sources/study",
  ))
})
