function colLetter(index) {
  let n = index;
  let s = "";
  while (n > 0) {
    const m = (n - 1) % 26;
    s = String.fromCharCode(65 + m) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

function alreadyInRepo(row) {
  const status = row["Evidence status"] ?? "";
  if (status.includes("Local PDF") || status.includes("source page")) return "Yes";
  if (status.includes("provenance gap")) return "Partial / verify";
  return "No";
}

function manualFetchNeeded(row) {
  const status = row["Evidence status"] ?? "";
  if (status.includes("External") || status.includes("provenance gap")) return "Yes";
  return "No";
}

function defaultStandardsUse(row) {
  if (row["Standards-use class"]) return row["Standards-use class"];
  const coverage = String(row.Coverage ?? row["Technique family"] ?? "").toLowerCase();
  if (coverage.includes("review")) return "Source finder / context";
  if (coverage.includes("speciation")) return "Speciation/method support";
  if (coverage.includes("method")) return "Method support / possible occurrence";
  if (coverage.includes("removal") || coverage.includes("degumming") || coverage.includes("bleaching") || coverage.includes("membrane")) {
    return "Removal/process-control evidence";
  }
  if (coverage.includes("direct oil") || coverage.includes("occurrence")) return "Benchmark candidate";
  if (row["Supply-chain stage"]) return "Supply-chain mitigation evidence";
  return "Evidence candidate";
}

function cellValue(row, header) {
  if (header === "Already in repo?") return alreadyInRepo(row);
  if (header === "Manual fetch needed?") return manualFetchNeeded(row);
  if (header === "Standards-use class") return defaultStandardsUse(row);
  return row[header] ?? "";
}

function writeTable(sheetName, headers, rows, widths) {
  const sheet = workbook.worksheets.add(sheetName);
  const data = [headers, ...rows.map((row) => headers.map((header) => cellValue(row, header)))];
  const lastCol = colLetter(headers.length);
  const range = sheet.getRange(`A1:${lastCol}${data.length}`);
  range.write(data);

  sheet.freezePanes.freezeRows(1);
  range.format.wrapText = true;
  range.format.verticalAlignment = "top";
  range.format.font = { name: "Aptos", size: 10, color: "#111827" };

  const headerRange = sheet.getRange(`A1:${lastCol}1`);
  headerRange.format.fill = "#1f4e79";
  headerRange.format.font = { name: "Aptos", size: 10, bold: true, color: "#ffffff" };
  headerRange.format.horizontalAlignment = "center";
  headerRange.format.verticalAlignment = "center";

  for (let i = 0; i < headers.length; i += 1) {
    const letter = colLetter(i + 1);
    const width = widths[headers[i]] ?? 160;
    sheet.getRange(`${letter}1:${letter}${data.length}`).format.columnWidthPx = width;
  }

  const statusCol = headers.indexOf("Evidence status") + 1;
  if (statusCol > 0) {
    const letter = colLetter(statusCol);
    sheet.getRange(`${letter}2:${letter}${data.length}`).format.fill = "#eef6ff";
  }

  const priorityCol = headers.indexOf("Priority") + 1;
  if (priorityCol > 0) {
    const letter = colLetter(priorityCol);
    sheet.getRange(`${letter}2:${letter}${data.length}`).format.horizontalAlignment = "center";
  }

  return sheet;
}

