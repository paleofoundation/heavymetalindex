function fetchAction(row) {
  const status = row["Evidence status"] ?? "";
  if (status.includes("provenance gap")) {
    return "Re-fetch PDF from DOI/publisher and verify SHA256; local batch path may be wrong.";
  }
  if (status.includes("External PDF")) {
    return "Download PDF from PDF URL, preserve raw file, then create source page and route evidence.";
  }
  if (status.includes("External DOI")) {
    return "Fetch PDF or publisher full text from DOI URL; preserve raw file before ingest.";
  }
  return "Already local or source-page staged; no manual fetch needed.";
}

